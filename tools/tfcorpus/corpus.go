// CorpusRef pins one extracted corpus source.
type CorpusRef struct {
	Name   string `yaml:"name" json:"name"`
	Repo   string `yaml:"repo" json:"repo"`
	Commit string `yaml:"commit" json:"commit"`
	Path   string `yaml:"path" json:"path"`
	Date   string `yaml:"date" json:"date"`
}

// Assertion is a REST check for an apply case. `Before` runs after apply,
// `After` after destroy (use Status: 404 there).
type Assertion struct {
	Phase    string   `yaml:"phase"` // before | after
	URL      string   `yaml:"url"`
	Contains []string `yaml:"contains,omitempty"`
	Status   int      `yaml:"status,omitempty"`
}

// ManifestCase is one extracted example (or scenario) turned into a case.
type ManifestCase struct {
	// Name is stable across provider bumps: <doc-base>-example-<n> for a
	// provider-docs block, <service-dir>/<sample-dir> for a samples scenario.
	Name string `yaml:"name"`
	// Source is a CorpusRef.Name.
	Source string `yaml:"source"`
	// File is the doc or tf file, relative to the corpus root.
	File  string `yaml:"file"`
	Block int    `yaml:"block,omitempty"`
	// ResourceTypes are the provider resource types the example declares.
	ResourceTypes []string `yaml:"resource_types"`
	// Service is the coverage-inventory service of the first resource type.
	Service string `yaml:"service"`
	// Mode is plan (plan-only triage) or apply (curated allowlist).
	Mode string `yaml:"mode"`
	// Status is candidate (run) or excluded (recorded, with a reason).
	Status string      `yaml:"status"`
	Reason string      `yaml:"reason,omitempty"`
	Assert []Assertion `yaml:"assert,omitempty"`
}

// Manifest is tests/integration/gcp/terraform/corpus.yaml.
type Manifest struct {
	Provider        string         `yaml:"provider"`
	ProviderVersion string         `yaml:"provider_version"`
	Corpora         []CorpusRef    `yaml:"corpora"`
	Cases           []ManifestCase `yaml:"cases"`
}

// Case modes and statuses.
const (
	ModePlan  = "plan"
	ModeApply = "apply"

	StatusCandidate = "candidate"
	StatusExcluded  = "excluded"
)

// LoadManifest reads a manifest. A missing file is an empty manifest so
// -discover can create it.
func LoadManifest(path string) (*Manifest, error) {
	raw, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return &Manifest{Provider: "hashicorp/google", ProviderVersion: "7.46.2"}, nil
	}
	if err != nil {
		return nil, fmt.Errorf("read manifest (%s): %w", path, err)
	}
	var m Manifest
	if err := yaml.Unmarshal(raw, &m); err != nil {
		return nil, fmt.Errorf("parse manifest (%s): %w", path, err)
	}
	if m.Provider == "" {
		m.Provider = "hashicorp/google"
	}
	if err := m.validate(); err != nil {
		return nil, fmt.Errorf("manifest (%s): %w", path, err)
	}
	return &m, nil
}

func (m *Manifest) validate() error {
	seen := map[string]bool{}
	for _, c := range m.Cases {
		if c.Name == "" {
			return fmt.Errorf("case with empty name")
		}
		if seen[c.Name] {
			return fmt.Errorf("duplicate case %q", c.Name)
		}
		seen[c.Name] = true
		switch c.Mode {
		case ModePlan, ModeApply:
		default:
			return fmt.Errorf("case %q has mode %q (want plan|apply)", c.Name, c.Mode)
		}
		switch c.Status {
		case StatusCandidate, StatusExcluded:
		default:
			return fmt.Errorf("case %q has status %q (want candidate|excluded)", c.Name, c.Status)
		}
		if c.Status == StatusExcluded && strings.TrimSpace(c.Reason) == "" {
			return fmt.Errorf("excluded case %q has no reason", c.Name)
		}
	}
	return nil
}

// SaveManifest writes a deterministic manifest with a provenance header.
func SaveManifest(path string, m *Manifest) error {
	sort.SliceStable(m.Corpora, func(i, j int) bool { return m.Corpora[i].Name < m.Corpora[j].Name })
	sort.SliceStable(m.Cases, func(i, j int) bool { return m.Cases[i].Name < m.Cases[j].Name })
	var b strings.Builder
	b.WriteString(`# Terraform web-corpus manifest (wave plan TF2).
#
# Generated by ` + "`make gen-gcp-terraform-corpus`" + `; hand edits to
# mode/status/reason/assert survive a re-discovery. Do not vendor corpus HCL:
# this file names blocks, the tool extracts them at run time from a local
# checkout (TF_PROVIDER_DOCS, TF_SAMPLES_DIR).
#
#   mode:   plan  -> plan-only triage (-run)
#           apply -> curated allowlist apply/assert/re-plan/destroy (-apply)
#   status: candidate -> selected to run
#           excluded  -> recorded with a reason (unsupported service, deferred)
`)
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(m); err != nil {
		return err
	}
	if err := enc.Close(); err != nil {
		return err
	}
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}

// MergeCases keeps hand edits for a case that still exists: the mode (the apply
// allowlist) and assertions always, plus a manual exclusion (a reason that
// discovery did not generate). Everything else is recomputed, so a resource
// that becomes served stops being recorded as unsupported.
func MergeCases(old *Manifest, discovered []ManifestCase) []ManifestCase {
	prev := make(map[string]ManifestCase, len(old.Cases))
	for _, c := range old.Cases {
		prev[c.Name] = c
	}
	out := make([]ManifestCase, 0, len(discovered))
	for _, c := range discovered {
		if p, ok := prev[c.Name]; ok {
			if p.Mode != "" {
				c.Mode = p.Mode
			}
			c.Assert = p.Assert
			if p.Status == StatusExcluded && !generatedReason(p.Reason) {
				c.Status = StatusExcluded
				c.Reason = p.Reason
			}
		}
		if c.Status == "" {
			c.Status = StatusCandidate
		}
		if c.Mode == "" {
			c.Mode = ModePlan
		}
		out = append(out, c)
	}
	return out
}

// generatedReason reports whether discovery produced the exclusion, so a
// re-discovery may replace it.
func generatedReason(reason string) bool {
	return strings.HasPrefix(reason, "unsupported-service:") ||
		strings.HasPrefix(reason, "unsupported-service (data source):") ||
		strings.HasPrefix(reason, "helper-provider:") ||
		strings.HasPrefix(reason, "beta-provider:") ||
		strings.HasPrefix(reason, "provider-version:") ||
		strings.Contains(reason, "deferred")
}

// CoverageRow is the part of docs/fidelity/terraform-coverage.csv the corpus
// tool joins against.
type CoverageRow struct {
	ProviderResource string
	Service          string
	EmulatorState    string
	Classification   string
}

// LoadCoverage reads the TF1 inventory.
func LoadCoverage(path string) (map[string]CoverageRow, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, fmt.Errorf("read coverage inventory (%s): %w", path, err)
	}
	defer f.Close()
	r := csv.NewReader(f)
	header, err := r.Read()
	if err != nil {
		return nil, fmt.Errorf("coverage header: %w", err)
	}
	col := map[string]int{}
	for i, h := range header {
		col[strings.TrimSpace(h)] = i
	}
	for _, want := range []string{"provider_resource", "service", "emulator_state", "classification"} {
		if _, ok := col[want]; !ok {
			return nil, fmt.Errorf("coverage inventory has no %q column", want)
		}
	}
	out := map[string]CoverageRow{}
	for {
		rec, err := r.Read()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, err
		}
		row := CoverageRow{
			ProviderResource: rec[col["provider_resource"]],
			Service:          rec[col["service"]],
			EmulatorState:    rec[col["emulator_state"]],
			Classification:   rec[col["classification"]],
		}
		out[row.ProviderResource] = row
	}
	return out, nil
}
