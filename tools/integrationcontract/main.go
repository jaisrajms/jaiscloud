// Command integrationcontract renders docs/gcp/integration/contract.yaml from
// the Kubernetes manifests and the hand-authored scenario catalogue.
//
// The contract is the machine-readable half of the integration pack: an agent
// reads the topology, objects, images, environment and scenario steps from one
// versioned file instead of scraping prose. It is generated so it cannot drift
// from the manifests; `-check` fails when the committed file is stale.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
	"k8s.io/apimachinery/pkg/apis/meta/v1/unstructured"
	utilyaml "k8s.io/apimachinery/pkg/util/yaml"
)

const (
	apiVersion = "jaiscloud.dev/integration/v1"
	kind       = "IntegrationContract"

	header = `# GENERATED by "make gen-integration-contract" — do not edit by hand.
# Facts come from the manifests listed under metadata.sources; the playbook
# comes from docs/gcp/integration/playbook.yaml.
`
)

var defaultManifests = []string{
	"deploy/k8s/namespace.yaml",
	"deploy/k8s/postgres.yaml",
	"deploy/k8s/rbac.yaml",
	"deploy/k8s/rbac-admission-policy.yaml",
	"deploy/k8s/jaiscloud.yaml",
	"deploy/k8s/jaiscloud-gcp.yaml",
}

func main() {
	manifests := flag.String("manifests", strings.Join(defaultManifests, ","), "comma-separated manifests to read")
	playbook := flag.String("playbook", "docs/gcp/integration/playbook.yaml", "playbook to embed")
	out := flag.String("out", "docs/gcp/integration/contract.yaml", "output file")
	check := flag.Bool("check", false, "compare with -out instead of writing; exit 1 when stale")
	flag.Parse()

	files := splitList(*manifests)
	contract, err := buildContract(files, *playbook)
	if err != nil {
		fatalf("%v", err)
	}
	rendered, err := render(contract)
	if err != nil {
		fatalf("render: %v", err)
	}

	if *check {
		existing, err := os.ReadFile(*out)
		if err != nil {
			fatalf("read %s: %v (run make gen-integration-contract)", *out, err)
		}
		if bytes.Equal(existing, rendered) {
			fmt.Printf("integration contract is up to date: %s\n", *out)
			return
		}
		fmt.Fprintf(os.Stderr, "integration contract is stale: %s\nrun: make gen-integration-contract\n\n", *out)
		printDiff(*out, rendered)
		os.Exit(1)
	}

	if err := os.WriteFile(*out, rendered, 0o644); err != nil {
		fatalf("write %s: %v", *out, err)
	}
	fmt.Printf("wrote %s (%d objects)\n", *out, len(contract.Topology.Objects))
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "integrationcontract: "+format+"\n", args...)
	os.Exit(1)
}

func splitList(s string) []string {
	var out []string
	for _, p := range strings.Split(s, ",") {
		if p = strings.TrimSpace(p); p != "" {
			out = append(out, p)
		}
	}
	return out
}

// Contract is the emitted document. Field order here is the emitted order.
type Contract struct {
	APIVersion string         `yaml:"apiVersion"`
	Kind       string         `yaml:"kind"`
	Metadata   Metadata       `yaml:"metadata"`
	Topology   Topology       `yaml:"topology"`
	Images     []Image        `yaml:"images"`
	Env        []EnvGroup     `yaml:"env"`
	Playbook   map[string]any `yaml:"playbook"`
}

type Metadata struct {
	Generator string   `yaml:"generator"`
	Sources   []string `yaml:"sources"`
	Notes     string   `yaml:"notes"`
}

type Topology struct {
	Namespaces []Namespace `yaml:"namespaces"`
	Objects    []Object    `yaml:"objects"`
}

type Namespace struct {
	Name      string            `yaml:"name"`
	Labels    map[string]string `yaml:"labels,omitempty"`
	Role      string            `yaml:"role,omitempty"`
	Substrate string            `yaml:"substrate,omitempty"`
}

// Object is the normalised view of one manifest document. Optional fields are
// omitted so the file stays readable.
type Object struct {
	Kind      string            `yaml:"kind"`
	Name      string            `yaml:"name"`
	Namespace string            `yaml:"namespace,omitempty"`
	Labels    map[string]string `yaml:"labels,omitempty"`

	// Workloads (Deployment).
	Replicas       *int64      `yaml:"replicas,omitempty"`
	Strategy       string      `yaml:"strategy,omitempty"`
	ServiceAccount string      `yaml:"serviceAccount,omitempty"`
	Containers     []Container `yaml:"containers,omitempty"`
	Claims         []string    `yaml:"claims,omitempty"`

	// Services.
	Type  string `yaml:"type,omitempty"`
	Ports []Port `yaml:"ports,omitempty"`

	// ConfigMaps and Secrets.
	Data map[string]string `yaml:"data,omitempty"`
	Keys []string          `yaml:"keys,omitempty"` // Secret: key names only, never values.

	// PVCs.
	AccessModes []string `yaml:"accessModes,omitempty"`
	Storage     string   `yaml:"storage,omitempty"`

	// ServiceAccounts and RBAC.
	Automount *bool     `yaml:"automountServiceAccountToken,omitempty"`
	RoleRef   *RoleRef  `yaml:"roleRef,omitempty"`
	Subjects  []Subject `yaml:"subjects,omitempty"`
}

type Container struct {
	Name       string   `yaml:"name"`
	Image      string   `yaml:"image"`
	PullPolicy string   `yaml:"imagePullPolicy,omitempty"`
	Ports      []Port   `yaml:"ports,omitempty"`
	Env        []EnvVar `yaml:"env,omitempty"`
	EnvFrom    []string `yaml:"envFrom,omitempty"`
}

type Port struct {
	Name       string `yaml:"name,omitempty"`
	Port       int64  `yaml:"port"`
	TargetPort string `yaml:"targetPort,omitempty"`
	NodePort   int64  `yaml:"nodePort,omitempty"`
}

type EnvVar struct {
	Name  string `yaml:"name"`
	Value string `yaml:"value,omitempty"`
	From  string `yaml:"from,omitempty"` // secret:<name>/<key>, configMap:<name>/<key>, field:<path>
}

type RoleRef struct {
	Kind string `yaml:"kind"`
	Name string `yaml:"name"`
}

type Subject struct {
	Kind      string `yaml:"kind"`
	Name      string `yaml:"name"`
	Namespace string `yaml:"namespace,omitempty"`
}

type Image struct {
	Workload   string `yaml:"workload"`
	Image      string `yaml:"image"`
	PullPolicy string `yaml:"pullPolicy,omitempty"`
}

type EnvGroup struct {
	Workload string            `yaml:"workload"`
	Values   map[string]string `yaml:"values"`
}

func buildContract(manifestPaths []string, playbookPath string) (*Contract, error) {
	objects, configMaps, err := parseManifests(manifestPaths)
	if err != nil {
		return nil, err
	}
	sort.Slice(objects, func(i, j int) bool {
		a, b := objects[i], objects[j]
		if a.Namespace != b.Namespace {
			return a.Namespace < b.Namespace
		}
		if a.Kind != b.Kind {
			return a.Kind < b.Kind
		}
		return a.Name < b.Name
	})
	// A few objects are declared in two manifests on purpose (the GCP
	// Namespace/ServiceAccount appear in both namespace.yaml/rbac.yaml and
	// jaiscloud-gcp.yaml so the one-file install works). The contract lists each
	// identity once.
	objects = dedupe(objects)

	contract := &Contract{
		APIVersion: apiVersion,
		Kind:       kind,
		Metadata: Metadata{
			Generator: "tools/integrationcontract",
			Sources:   manifestPaths,
			Notes: "Images, ports, env and claims are the manifest defaults. " +
				"Secret values are deliberately omitted (key names only). " +
				"Run make check-integration-contract after changing a manifest.",
		},
		Topology: Topology{Objects: objects},
	}
	for _, o := range objects {
		if o.Kind == "Namespace" {
			contract.Topology.Namespaces = append(contract.Topology.Namespaces, Namespace{
				Name:      o.Name,
				Labels:    o.Labels,
				Role:      o.Labels["jaiscloud.io/role"],
				Substrate: o.Labels["jaiscloud.io/substrate"],
			})
		}
	}
	contract.Images, contract.Env = summarise(objects, configMaps)

	playbook, err := loadYAMLMap(playbookPath)
	if err != nil {
		return nil, fmt.Errorf("playbook: %w", err)
	}
	contract.Playbook = playbook
	return contract, nil
}

// dedupe removes repeated identities, keeping the first (documents that are
// declared twice are byte-identical by design).
func dedupe(objects []Object) []Object {
	out := objects[:0]
	for _, o := range objects {
		if len(out) > 0 {
			prev := out[len(out)-1]
			if prev.Kind == o.Kind && prev.Namespace == o.Namespace && prev.Name == o.Name {
				continue
			}
		}
		out = append(out, o)
	}
	return out
}

// parseManifests decodes every document and returns the normalised objects plus
// the ConfigMaps by "namespace/name" (so envFrom can be expanded).
func parseManifests(paths []string) ([]Object, map[string]map[string]string, error) {
	var objects []Object
	configMaps := map[string]map[string]string{}
	for _, path := range paths {
		f, err := os.Open(path)
		if err != nil {
			return nil, nil, err
		}
		dec := utilyaml.NewYAMLOrJSONDecoder(f, 4096)
		for {
			var u unstructured.Unstructured
			if err := dec.Decode(&u); err != nil {
				if errors.Is(err, io.EOF) {
					break
				}
				f.Close()
				return nil, nil, fmt.Errorf("%s: %w", path, err)
			}
			if len(u.Object) == 0 {
				continue
			}
			obj, cm, err := normalise(&u)
			if err != nil {
				f.Close()
				return nil, nil, fmt.Errorf("%s %s/%s: %w", path, u.GetKind(), u.GetName(), err)
			}
			if cm != nil {
				configMaps[u.GetNamespace()+"/"+u.GetName()] = cm
			}
			objects = append(objects, obj)
		}
		f.Close()
	}
	return objects, configMaps, nil
}

func normalise(u *unstructured.Unstructured) (Object, map[string]string, error) {
	o := Object{
		Kind:      u.GetKind(),
		Name:      u.GetName(),
		Namespace: u.GetNamespace(),
		Labels:    u.GetLabels(),
	}
	var cmData map[string]string
	switch u.GetKind() {
	case "Deployment":
		replicas, found, err := unstructured.NestedInt64(u.Object, "spec", "replicas")
		if err != nil {
			return o, nil, err
		}
		if found {
			o.Replicas = &replicas
		}
		o.Strategy, _, _ = unstructured.NestedString(u.Object, "spec", "strategy", "type")
		o.ServiceAccount, _, _ = unstructured.NestedString(u.Object, "spec", "template", "spec", "serviceAccountName")
		vols, _, _ := unstructured.NestedSlice(u.Object, "spec", "template", "spec", "volumes")
		for _, v := range vols {
			m, _ := v.(map[string]any)
			if claim, ok, _ := unstructured.NestedString(m, "persistentVolumeClaim", "claimName"); ok {
				o.Claims = append(o.Claims, claim)
			}
		}
		sort.Strings(o.Claims)
		cs, _, _ := unstructured.NestedSlice(u.Object, "spec", "template", "spec", "containers")
		for _, c := range cs {
			container, err := normaliseContainer(c)
			if err != nil {
				return o, nil, err
			}
			o.Containers = append(o.Containers, container)
		}
	case "Service":
		o.Type, _, _ = unstructured.NestedString(u.Object, "spec", "type")
		ports, _, _ := unstructured.NestedSlice(u.Object, "spec", "ports")
		for _, p := range ports {
			m, _ := p.(map[string]any)
			port := Port{}
			port.Name, _, _ = unstructured.NestedString(m, "name")
			port.Port, _, _ = unstructured.NestedInt64(m, "port")
			switch tp := m["targetPort"].(type) {
			case int64:
				port.TargetPort = fmt.Sprintf("%d", tp)
			case float64:
				port.TargetPort = fmt.Sprintf("%d", int64(tp))
			case string:
				port.TargetPort = tp
			}
			port.NodePort, _, _ = unstructured.NestedInt64(m, "nodePort")
			o.Ports = append(o.Ports, port)
		}
	case "ConfigMap":
		data, _, _ := unstructured.NestedStringMap(u.Object, "data")
		o.Data = data
		cmData = data
	case "Secret":
		o.Type, _, _ = unstructured.NestedString(u.Object, "type")
		for _, field := range []string{"data", "stringData"} {
			m, _, _ := unstructured.NestedMap(u.Object, field)
			for k := range m {
				o.Keys = append(o.Keys, k)
			}
		}
		sort.Strings(o.Keys)
	case "PersistentVolumeClaim":
		modes, _, _ := unstructured.NestedStringSlice(u.Object, "spec", "accessModes")
		o.AccessModes = modes
		o.Storage, _, _ = unstructured.NestedString(u.Object, "spec", "resources", "requests", "storage")
	case "ServiceAccount":
		automount, found, _ := unstructured.NestedBool(u.Object, "automountServiceAccountToken")
		if found {
			o.Automount = &automount
		}
	case "RoleBinding", "ClusterRoleBinding":
		ref := &RoleRef{}
		ref.Kind, _, _ = unstructured.NestedString(u.Object, "roleRef", "kind")
		ref.Name, _, _ = unstructured.NestedString(u.Object, "roleRef", "name")
		o.RoleRef = ref
		subs, _, _ := unstructured.NestedSlice(u.Object, "subjects")
		for _, s := range subs {
			m, _ := s.(map[string]any)
			sub := Subject{}
			sub.Kind, _, _ = unstructured.NestedString(m, "kind")
			sub.Name, _, _ = unstructured.NestedString(m, "name")
			sub.Namespace, _, _ = unstructured.NestedString(m, "namespace")
			o.Subjects = append(o.Subjects, sub)
		}
	}
	return o, cmData, nil
}

func normaliseContainer(raw any) (Container, error) {
	m, _ := raw.(map[string]any)
	c := Container{}
	c.Name, _, _ = unstructured.NestedString(m, "name")
	c.Image, _, _ = unstructured.NestedString(m, "image")
	c.PullPolicy, _, _ = unstructured.NestedString(m, "imagePullPolicy")
	ports, _, _ := unstructured.NestedSlice(m, "ports")
	for _, p := range ports {
		pm, _ := p.(map[string]any)
		port := Port{}
		port.Name, _, _ = unstructured.NestedString(pm, "name")
		port.Port, _, _ = unstructured.NestedInt64(pm, "containerPort")
		c.Ports = append(c.Ports, port)
	}
	envs, _, _ := unstructured.NestedSlice(m, "env")
	for _, e := range envs {
		em, _ := e.(map[string]any)
		ev := EnvVar{}
		ev.Name, _, _ = unstructured.NestedString(em, "name")
		if v, ok, _ := unstructured.NestedString(em, "value"); ok {
			ev.Value = v
		} else if name, ok, _ := unstructured.NestedString(em, "valueFrom", "secretKeyRef", "name"); ok {
			key, _, _ := unstructured.NestedString(em, "valueFrom", "secretKeyRef", "key")
			ev.From = "secret:" + name + "/" + key
		} else if name, ok, _ := unstructured.NestedString(em, "valueFrom", "configMapKeyRef", "name"); ok {
			key, _, _ := unstructured.NestedString(em, "valueFrom", "configMapKeyRef", "key")
			ev.From = "configMap:" + name + "/" + key
		} else if path, ok, _ := unstructured.NestedString(em, "valueFrom", "fieldRef", "fieldPath"); ok {
			ev.From = "field:" + path
		}
		c.Env = append(c.Env, ev)
	}
	from, _, _ := unstructured.NestedSlice(m, "envFrom")
	for _, f := range from {
		fm, _ := f.(map[string]any)
		if name, ok, _ := unstructured.NestedString(fm, "configMapRef", "name"); ok {
			c.EnvFrom = append(c.EnvFrom, "configMap:"+name)
		}
		if name, ok, _ := unstructured.NestedString(fm, "secretRef", "name"); ok {
			c.EnvFrom = append(c.EnvFrom, "secret:"+name)
		}
	}
	return c, nil
}

// summarise derives the convenience images/env tables from the artefacts and
// the ConfigMaps they reference.
func summarise(objects []Object, configMaps map[string]map[string]string) ([]Image, []EnvGroup) {
	var images []Image
	envByName := map[string]map[string]string{}
	for _, o := range objects {
		if o.Kind != "Deployment" {
			continue
		}
		for _, c := range o.Containers {
			if c.Image != "" {
				images = append(images, Image{Workload: o.Name, Image: c.Image, PullPolicy: c.PullPolicy})
			}
			values := map[string]string{}
			for _, from := range c.EnvFrom {
				if name, ok := strings.CutPrefix(from, "configMap:"); ok {
					for k, v := range configMaps[o.Namespace+"/"+name] {
						values[k] = v
					}
				}
			}
			for _, e := range c.Env {
				switch {
				case e.From != "":
					values[e.Name] = "<" + e.From + ">"
				default:
					values[e.Name] = e.Value
				}
			}
			if len(values) > 0 {
				if envByName[o.Name] == nil {
					envByName[o.Name] = map[string]string{}
				}
				for k, v := range values {
					envByName[o.Name][k] = v
				}
			}
		}
	}
	sort.Slice(images, func(i, j int) bool { return images[i].Workload < images[j].Workload })
	var workloads []string
	for w := range envByName {
		workloads = append(workloads, w)
	}
	sort.Strings(workloads)
	var env []EnvGroup
	for _, w := range workloads {
		env = append(env, EnvGroup{Workload: w, Values: envByName[w]})
	}
	return images, env
}

func loadYAMLMap(path string) (map[string]any, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var m map[string]any
	if err := yaml.Unmarshal(b, &m); err != nil {
		return nil, err
	}
	return m, nil
}

func render(c *Contract) ([]byte, error) {
	var body bytes.Buffer
	enc := yaml.NewEncoder(&body)
	enc.SetIndent(2)
	if err := enc.Encode(c); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return append([]byte(header), body.Bytes()...), nil
}

func printDiff(path string, rendered []byte) {
	tmp, err := os.CreateTemp("", "integration-contract-*.yaml")
	if err != nil {
		return
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(rendered); err != nil {
		tmp.Close()
		return
	}
	tmp.Close()
	cmd := exec.Command("diff", "-u", path, tmp.Name())
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	_ = cmd.Run() // exit status 1 just means "differs"; the caller decides
}
