// defaultScenarioPath is the committed generated dataset consumed by
// tests/gcpparity. It lives with the parity suite (not in tools/) because it is
// compiled into that package, and it is generated from the catalog so the
// values and the classifications cannot drift apart.
const defaultScenarioPath = "tests/gcpparity/zz_fieldcoverage_generated.go"

// RenderScenarios renders the generated Go file. Rendering is deterministic, so
// -check can compare the committed file byte for byte and a definition or
// classification change that was not regenerated fails the gate.
func RenderScenarios(set *ScenarioSet) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by \"go run -tags gcp_conformance ./tools/fieldgen -gen\". DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// Source of truth: docs/fidelity/field-coverage.csv (classifications) joined with the\n")
	b.WriteString("// definitions it was derived from (wire types) and tools/fieldgen/scenario-values.yaml\n")
	b.WriteString("// (values a type cannot determine). Every roundtrip row has a value here, every\n")
	b.WriteString("// output-only/immutable row has a negative write, and the parity suite fails when a\n")
	b.WriteString("// value is not placed by a resource driver — so a new field cannot enter the catalog\n")
	b.WriteString("// without a scenario.\n\n")
	b.WriteString("//go:build gcp_parity\n\n")
	b.WriteString("package gcpparity\n\n")

	b.WriteString("// generatedFieldValues is the generated per-field data the round-trip suite drives.\n")
	b.WriteString("var generatedFieldValues = []generatedField{\n")
	for _, v := range set.Values {
		fmt.Fprintf(&b, "\t{Service: %s, Resource: %s, Transport: %s, Field: %s, Path: %s, Kind: %s, Repeated: %t, Value: %s, Ref: %s, Update: %t, UpdateValue: %s, Behavior: %s, Coverage: %s},\n",
			goString(v.Service), goString(v.Resource), goString(v.Transport), goString(v.Field),
			goString(v.Path), goString(v.Kind), v.Repeated, goString(v.Value), goString(v.Ref),
			v.Update, goString(v.UpdateVal), goString(v.Behavior), goString(v.Coverage))
	}
	b.WriteString("}\n\n")

	b.WriteString("// generatedFieldWriteAttempts is the generated negative-write data: output-only\n")
	b.WriteString("// fields attempted at create, immutable fields attempted at update.\n")
	b.WriteString("var generatedFieldWriteAttempts = []generatedWriteAttempt{\n")
	for _, a := range set.Attempts {
		fmt.Fprintf(&b, "\t{Service: %s, Resource: %s, Transport: %s, Field: %s, Path: %s, Kind: %s, At: %s, Value: %s, Coverage: %s},\n",
			goString(a.Service), goString(a.Resource), goString(a.Transport), goString(a.Field),
			goString(a.Path), goString(a.Kind), goString(a.At), goString(a.Value), goString(a.Coverage))
	}
	b.WriteString("}\n")
	return b.Bytes(), nil
}

func goString(s string) string { return strconv.Quote(s) }

// WriteScenarios writes the rendered file atomically.
func WriteScenarios(path string, set *ScenarioSet) error {
	raw, err := RenderScenarios(set)
	if err != nil {
		return err
	}
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, ".field-scenarios-*.go")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(raw); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmp.Name(), path); err != nil {
		return err
	}
	return os.Chmod(path, 0o644)
}

// CheckScenarios fails when the committed generated file is not exactly what the
// catalog and definitions produce.
func CheckScenarios(path string, set *ScenarioSet) error {
	want, err := RenderScenarios(set)
	if err != nil {
		return err
	}
	got, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("read generated scenarios (%s): %w (run `make gen-gcp-field-coverage`)", path, err)
	}
	if bytes.Equal(got, want) {
		return nil
	}
	return fmt.Errorf("%s is stale: the catalog/definitions/scenario-values changed and the file was not regenerated\n  run `make gen-gcp-field-coverage` and commit the result (a roundtrip row with no scenario is a gate failure)", path)
}

// ScenarioStats summarises the dataset for the CLI.
type ScenarioStats struct {
	Values    int
	Attempts  int
	Resources int
	Updates   int
	Refs      int
}

func scenarioStats(set *ScenarioSet) ScenarioStats {
	st := ScenarioStats{Values: len(set.Values), Attempts: len(set.Attempts), Resources: len(resources(set))}
	for _, v := range set.Values {
		if v.Update {
			st.Updates++
		}
		if v.Ref != "" {
			st.Refs++
		}
	}
	return st
}

func resources(set *ScenarioSet) map[string]bool {
	out := map[string]bool{}
	for _, v := range set.Values {
		out[v.Service+"/"+v.Resource] = true
	}
	for _, a := range set.Attempts {
		out[a.Service+"/"+a.Resource] = true
	}
	return out
}

// validateScenarioCoverage is the structural contract of the generated dataset:
// every classified row that needs a scenario produced one, and nothing else did.
func validateScenarioCoverage(universe *Universe, rows []Row, set *ScenarioSet) error {
	values := map[string]bool{}
	for _, v := range set.Values {
		values[v.Service+"/"+v.Transport+"/"+v.Resource+"/"+v.Field] = true
	}
	attempts := map[string]bool{}
	for _, a := range set.Attempts {
		attempts[a.Service+"/"+a.Transport+"/"+a.Resource+"/"+a.Field] = true
	}
	byKey := map[string]Row{}
	for _, r := range rows {
		byKey[r.Key()] = r
	}
	var problems []string
	for _, f := range universe.Fields {
		row, ok := byKey[f.Key()]
		if !ok || row.Coverage == "" {
			continue // already reported by the row/classification gate
		}
		switch row.Coverage {
		case CoverageRoundtrip:
			if !values[f.Key()] {
				problems = append(problems, "roundtrip field has no generated value: "+f.Key())
			}
		case CoverageOutputOnly, CoverageImmutable:
			if !attempts[f.Key()] {
				problems = append(problems, "negative-write field has no generated attempt: "+f.Key())
			}
		}
	}
	sort.Strings(problems)
	if len(problems) > 0 {
		const limit = 20
		shown := problems
		if len(shown) > limit {
			shown = shown[:limit]
		}
		return fmt.Errorf("generated scenarios are incomplete (%d problem(s)):\n  %s", len(problems), joinLines(shown))
	}
	return nil
}

func joinLines(lines []string) string {
	out := ""
	for i, l := range lines {
		if i > 0 {
			out += "\n  "
		}
		out += l
	}
	return out
}
